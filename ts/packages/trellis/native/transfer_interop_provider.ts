import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { Result } from "@oatscenter/result";
import { createInterface } from "node:readline";
import { participants } from "../../../../integration/fixtures/runtime/packages/runtime-trellis/index.js";
import { TrellisService } from "../service/mod.ts";

const stdin = createInterface({ input: process.stdin });
const messages = stdin[Symbol.asyncIterator]();
const first = await messages.next();
if (first.done) throw new Error("provider identity required");
const config = JSON.parse(first.value) as { trellisUrl: string; seed: string };
const service = await TrellisService.connect({
  ...config,
  participant: participants.Provider.participant,
}).orThrow();
try {
  const store = await service.store.files.open().orThrow();
  await store
    .put(
      "download",
      Uint8Array.from({ length: 5 * 1024 * 1024 + 7 }, (_, i) => i % 251),
    )
    .orThrow();
  await service.handleDownload(async ({ input, context }) => {
    assert(context.caller.type === "verified");
    const transfer = await service
      .createTransfer({
        direction: "receive",
        store: "files",
        key: "download",
        sessionKey: context.caller.sessionPublicKey,
        connectionId: context.caller.runtimeId,
        contextDigest: context.caller.authorityDigest,
        permission: context.permission,
        requiredCapabilities: context.requiredCapabilities,
        inboxPrefix: context.inboxPrefix,
      })
      .orThrow();
    return Result.ok({ ...input, transfer });
  });
  await service.handleUpload(async ({ input, op, transfer }) => {
    assert(transfer);
    const body = await transfer.stream().orThrow();
    let offset = 0;
    for await (const chunk of body) {
      for (const byte of chunk) assert.equal(byte, offset++ % 251);
    }
    assert.equal(offset, 5 * 1024 * 1024 + 7);
    return await op.complete(input).orThrow();
  });
  // A `stream` Operation reads the caller's bytes as they arrive.
  await service.handleIngest(async ({ op, transfer }) => {
    assert(transfer);
    const hash = createHash("sha256");
    let size = 0;
    for await (const chunk of await transfer.stream().orThrow()) {
      for (const byte of chunk) assert.equal(byte, size++ % 251);
      hash.update(chunk);
    }
    const info = await transfer.completed().orThrow();
    assert.equal(info.size, size);
    return await op
      .complete({ value: `node:${size}:SHA-256=${hash.digest("base64url")}` })
      .orThrow();
  });
  // Generated bytes stream from a provider source with declared metadata;
  // `lie` declares the digest of different same-sized bytes.
  await service.handleGenerate(async ({ input, context }) => {
    assert(context.caller.type === "verified");
    const lie = input.value === "lie";
    const size = lie ? 4096 : Number(input.value);
    const bytes = Uint8Array.from({ length: size }, (_, i) => i % 251);
    const transfer = await service
      .createTransfer({
        direction: "receive",
        stream: (async function* () {
          if (bytes.length) yield bytes;
        })(),
        info: {
          key: "generated",
          size,
          updatedAt: new Date().toISOString(),
          digest: `SHA-256=${createHash("sha256")
            .update(lie ? new Uint8Array(size) : bytes)
            .digest("base64url")}`,
          metadata: {},
        },
        sessionKey: context.caller.sessionPublicKey,
        connectionId: context.caller.runtimeId,
        contextDigest: context.caller.authorityDigest,
        permission: context.permission,
        requiredCapabilities: context.requiredCapabilities,
        inboxPrefix: context.inboxPrefix,
      })
      .orThrow();
    return Result.ok({ ...input, transfer });
  });
  console.log(JSON.stringify({ stage: "ready" }));
  await messages.next();
} finally {
  stdin.close();
  await service.stop();
}
